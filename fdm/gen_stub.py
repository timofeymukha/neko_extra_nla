#!/usr/bin/env python3
"""Writes fdm_dev_stub.f90 from the interface block of box_fdm.f90 (or into argv[1]): every
device entry point as a routine that stops with an error (a CPU build links
against these; the host path never calls them)."""
import re, pathlib, sys
here = pathlib.Path(__file__).parent
src = (here / 'box_fdm.f90').read_text()
block = src[src.index('  interface\n'):src.index('  end interface\n')]
# join continuation lines
block = re.sub(r'&\s*\n\s*', '', block)
out = ['!> Stand-ins for fdm_dev.hip in a CPU-only build (makeneko box_fdm.f90',
       '!! fdm_dev_stub.f90): the device entry points are never called there; the',
       '!! host path does the solve. Generated by gen_stub.py from the interface',
       '!! block of box_fdm.f90; do not edit.']
for m in re.finditer(r'^\s*(function|subroutine)\s+(\w+)\((.*?)\)(.*?)\n(.*?)^\s*end (function|subroutine) \w+',
                     block, re.S | re.M):
    kind, name, args, tail, body = m.group(1), m.group(2), m.group(3), m.group(4), m.group(5)
    res = re.search(r'result\((\w+)\)', tail)
    decls = [l.strip() for l in body.splitlines() if l.strip() and not l.strip().startswith('import')]
    out.append(f'{kind} {name}({args}){tail}')
    out.append('  use, intrinsic :: iso_c_binding')
    out.append('  use utils, only : neko_error')
    out += ['  ' + d for d in decls]
    out.append(f"  call neko_error('fdm: device routine {name} called in a CPU build')")
    if res:
        rname = res.group(1)
        rtype = [d for d in decls if re.search(r'::\s*' + rname + r'\b', d)][0]
        if 'c_ptr' in rtype:
            out.append(f'  {rname} = c_null_ptr')
        else:
            out.append(f'  {rname} = 0')
    out.append(f'end {kind} {name}')
def wrap(line, width=100):
    # free-form continuation at commas (gfortran's default limit is 132)
    res = []
    while len(line) > width:
        cut = line.rfind(', ', 0, width)
        if cut < 0:
            break
        res.append(line[:cut + 1] + ' &')
        line = '     ' + line[cut + 2:]
    return res + [line]
lines = [w for l in out for w in wrap(l)]
out_path = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else here / 'fdm_dev_stub.f90'
out_path.write_text('\n'.join(lines) + '\n')
